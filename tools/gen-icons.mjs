// Generates src/Vigo.App/Controls/FluentIcons.g.cs: Fluent System Icons glyphs (20 regular)
// used by the mockups. Usage: node tools/gen-icons.mjs <FluentSystemIcons-Regular.json> <mockups...>
import { readFileSync, writeFileSync } from 'node:fs';

const [jsonPath, ...designs] = process.argv.slice(2);
const map = JSON.parse(readFileSync(jsonPath, 'utf8'));
const names = new Set();
for (const d of designs) {
  const src = readFileSync(d, 'utf8');
  for (const m of src.matchAll(/\bn="([a-z_]+)"/g)) names.add(m[1]);
  for (const m of src.matchAll(/\bi: *'([a-z_]+)'/g)) names.add(m[1]);
  for (const m of src.matchAll(/\btb\('([a-z_]+)'/g)) names.add(m[1]);
  for (const m of src.matchAll(/'(arrow_[a-z_]+|[a-z]+_[a-z_]+)'/g)) if (map[`ic_fluent_${m[1]}_20_regular`]) names.add(m[1]);
}
// Used by the application but absent from the mockups (J4.7: windows; file lists: change kinds, path / tree mode, grip).
['home', 'folder', 'circle', 'more_horizontal', 'window_new', 'window_arrow_up', 'arrow_exit',
  'document_copy', 'tree_evergreen', 'list', 'text_bullet_list_tree', 're_order_dots_horizontal', 'keyboard',
  // Azure DevOps work item types (epic, feature, user story, task, issue / impediment).
  'crown', 'trophy', 'book', 'clipboard_task', 'flag',
  // "Statistiques" entry of the left panel (J7.14).
  'data_bar_vertical',
  // "Aide en ligne" of the toolbar and the palette.
  'question_circle',
  // Eye of the left panel rows: hides a branch, tag, stash or worktree from the graph (J7.17).
  'eye', 'eye_off',
  // Diff layout toggle (J9.50): unified (rows) and side-by-side (columns).
  'layout_row_two', 'layout_column_two'].forEach(n => names.add(n));
const esc = cp => String.fromCharCode(92) + (cp > 0xFFFF ? 'U' + cp.toString(16).toUpperCase().padStart(8, '0') : 'u' + cp.toString(16).toUpperCase().padStart(4, '0'));
const pascal = n => n.split('_').map(p => p[0].toUpperCase() + p.slice(1)).join('');
const found = [], missing = [];
for (const n of [...names].sort()) {
  const cp = map[`ic_fluent_${n}_20_regular`] ?? map[`ic_fluent_${n}_24_regular`];
  if (cp === undefined) { missing.push(n); continue; }
  found.push(`    public const string ${pascal(n)} = "${esc(cp)}";`);
}
const byName = [...names].filter(n => !missing.includes(n)).sort()
  .map(n => `        "${n}" => ${pascal(n)},`).join('\n');
writeFileSync(new URL('../src/Vigo.App/Controls/FluentIcons.g.cs', import.meta.url),
`// <auto-generated> tools/gen-icons.mjs — Fluent System Icons (MIT), size 20 regular. </auto-generated>
#nullable enable
namespace Vigo.App.Controls;

public static class FluentIcons
{
${found.join('\n')}

    /// <summary>Glyph from the name used in the mockups (e.g. "arrow_upload").</summary>
    public static string FromName(string? name) => name switch
    {
${byName}
        _ => Circle,
    };
}
`);
console.log(`${found.length} icons; missing: ${missing.join(', ') || 'none'}`);
