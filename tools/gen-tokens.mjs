// Generates src/Vigo.App/Themes/Tokens.xaml from the CSS of the Claude Design design system.
// Usage: node tools/gen-tokens.mjs <VIGO.dc.html file (HTML entities accepted)>
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(process.argv[2], 'utf8').replace(/&quot;/g, '"');
const block = sel => {
  const i = src.indexOf(sel);
  if (i < 0) throw new Error(`Selector not found: ${sel}`);
  const s = src.indexOf('{', i), e = src.indexOf('}', s);
  return Object.fromEntries(src.slice(s + 1, e).split(';').map(d => d.trim()).filter(Boolean)
    .map(d => [d.slice(2, d.indexOf(':')).trim(), d.slice(d.indexOf(':') + 1).trim()]));
};
const dark = block(':root,[data-theme="dark"]');
const light = block('[data-theme="light"]');
const root = block(':root{--b1');

const hex2 = n => Math.round(n).toString(16).padStart(2, '0').toUpperCase();
function toArgb(v) {
  let m;
  if ((m = v.match(/^#([0-9a-f]{6})$/i))) return '#FF' + m[1].toUpperCase();
  if ((m = v.match(/^rgba\((\d+),(\d+),(\d+),([\d.]+)\)$/i)))
    return '#' + hex2(parseFloat(m[4]) * 255) + hex2(+m[1]) + hex2(+m[2]) + hex2(+m[3]);
  return null;
}
const pascal = k => k.split('-').map(p => p[0].toUpperCase() + p.slice(1)).join('');

function themeDict(key, vars) {
  const lines = [`        <ResourceDictionary x:Key="${key}">`];
  for (const [k, v] of Object.entries(vars)) {
    const c = toArgb(v);
    if (!c) continue; // shadows, etc.: translated by hand in Styles.xaml
    lines.push(`            <Color x:Key="Vigo${pascal(k)}Color">${c}</Color>`);
    lines.push(`            <SolidColorBrush x:Key="Vigo${pascal(k)}Brush" Color="${c}" />`);
  }
  lines.push('        </ResourceDictionary>');
  return lines.join('\n');
}

const lanes = Object.entries(root).filter(([k]) => /^b\d+$/.test(k))
  .map(([k, v]) => `    <Color x:Key="VigoLane${k.slice(1)}Color">${toArgb(v)}</Color>\n    <SolidColorBrush x:Key="VigoLane${k.slice(1)}Brush" Color="${toArgb(v)}" />`).join('\n');

const xaml = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED FILE by tools/gen-tokens.mjs from the Claude Design design system (VIGO.dc.html). Do not edit by hand. -->
<ResourceDictionary
    xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
    <ResourceDictionary.ThemeDictionaries>
${themeDict('Default', dark)}
${themeDict('Light', light)}
    </ResourceDictionary.ThemeDictionaries>

    <!-- Graph lane colors (same in light and dark) -->
${lanes}
</ResourceDictionary>
`;
writeFileSync(new URL('../src/Vigo.App/Themes/Tokens.xaml', import.meta.url), xaml);

// Same palette in C# for Win2D rendering (graph, diff): no XAML resource lookup
// on the drawing path, and no WinRT resource casts (unreliable under Native AOT).
const csColor = argb => `Color.FromArgb(0x${argb.slice(1, 3)}, 0x${argb.slice(3, 5)}, 0x${argb.slice(5, 7)}, 0x${argb.slice(7, 9)})`;
const csTheme = vars => Object.entries(vars).map(([k, v]) => [k, toArgb(v)]).filter(([, c]) => c)
  .map(([k, c]) => `        public static readonly Color ${pascal(k)} = ${csColor(c)};`).join('\n');
const csLanes = Object.entries(root).filter(([k]) => /^b\d+$/.test(k)).map(([, v]) => `        ${csColor(toArgb(v))},`).join('\n');
writeFileSync(new URL('../src/Vigo.App/Themes/DesignTokens.g.cs', import.meta.url),
`// <auto-generated> tools/gen-tokens.mjs — Claude Design design system (VIGO.dc.html). Do not edit. </auto-generated>
using Windows.UI;

namespace Vigo.App.Themes;

public static class DesignTokens
{
    /// <summary>Graph lane colors (--b1…--b10).</summary>
    public static readonly Color[] Lanes =
    [
${csLanes}
    ];

    public static class Dark
    {
${csTheme(dark)}
    }

    public static class Light
    {
${csTheme(light)}
    }
}
`);
console.log(`Tokens: ${Object.keys(dark).length} dark, ${Object.keys(light).length} light, lanes ${lanes.split('\n').length}`);
